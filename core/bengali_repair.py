# -*- coding: utf-8 -*-
"""
Bengali Font, Glyph & PDF Ligature Repair Engine.
Repairs broken Unicode Bengali text resulting from:
- PDF visual-order font CMaps (Chrome/Skia, SolaimanLipi, Nikosh)
- Broken PDF null bytes (\\x00, \\ufffe) in font ligatures
- Misplaced pre-kars (ি, ে, ৈ) placed before consonants instead of after
- Split composite vowels (ে + Consonant + া -> Consonant + ো)
- Broken table pipes inside Bengali words (e.g. জলু | াই -> জুলাই)
"""

import re


def repair_broken_bengali(text: str) -> str:
    """
    Repair visually disordered, decomposed, or null-byte corrupted Bengali text.
    100% deterministic and safe on already valid Unicode text.
    """
    if not text:
        return ""

    # 1. Unicode replacement / non-character marks
    text = text.replace("\ufeff", "").replace("\ufffe", "").replace("\ufffd", "")

    # 2. Table pipe splits inside words (e.g. জলু | াই -> জুলাই, খলু | | না -> খুলনা)
    text = re.sub(r'জলু\s*\|\s*াই', 'জুলাই', text)
    text = re.sub(r'জলু\s*াই', 'জুলাই', text)
    text = re.sub(r'খলু\s*\|\s*\|\s*না', 'খুলনা', text)
    text = re.sub(r'খলু\s*\|\s*না', 'খুলনা', text)

    # 3. Specific known PDF ligature / CMap / null-byte patterns
    ligature_fixes = [
        # মহাব্যবস্থাপক / সহকারী মহাব্যবস্থাপক / ব্যবস্থাপক
        (r'উপ-মহাব[\x00\s]*বস্থাপক', 'উপ-মহাব্যবস্থাপক'),
        (r'সহকারী\s*মহাব[\x00\s]*বস্থাপক', 'সহকারী মহাব্যবস্থাপক'),
        (r'মহাব[\x00\s]*বস্থাপক', 'মহাব্যবস্থাপক'),
        (r'ব[\x00\s]*বস্থাপক', 'ব্যবস্থাপক'),

        # ব্যাংকিং / ব্যাংক
        (r'অনলাইন\s+ব[\x00\s]*াংিকং', 'অনলাইন ব্যাংকিং'),
        (r'ব[\x00\s]*াংিকং', 'ব্যাংকিং'),
        (r'ব[\x00\s]*াংক', 'ব্যাংক'),

        # ডিপার্টমেন্ট / ডিপার্টমেন্টের / পার্টমেন্ট
        (r'িডপাট[\x00\s]*েমেন্টের', 'ডিপার্টমেন্টের'),
        (r'িডপাট[\x00\s]*েমেন্টর', 'ডিপার্টমেন্টের'),
        (r'িডপাট[\x00\s]*েমেন্ট', 'ডিপার্টমেন্টের'),
        (r'িডপাট[\x00\s]*েমন্ট', 'ডিপার্টমেন্ট'),
        (r'ডিপাট[\x00\s]*েমন্ট', 'ডিপার্টমেন্ট'),
        (r'পাট[\x00\s]*েমন্ট', 'পার্টমেন্ট'),

        # নৈমিত্তিক
        (r'[\x00\s]*নিমি[\x00\s]*ক', 'নৈমিত্তিক'),

        # ছুটির / ছুটিতে / ছুটি
        (r'ছু[\x00\s]*টর', 'ছুটির'),
        (r'ছু[\x00\s]*টেত', 'ছুটিতে'),
        (r'ছু[\x00\s]*টে', 'ছুটিতে'),
        (r'(?<![\u0980-\u09FF])ছু[\x00\s]*ট(?![\u0980-\u09FF])', 'ছুটি'),

        # প্রাপ্তব্য ভোগকৃত
        (r'প্রাপ্তব[\x00\s]+[\x00\s]*ভাগকৃত', 'প্রাপ্তব্য ভোগকৃত'),
        (r'প্রাপ্তব\x00', 'প্রাপ্তব্য'),
        (r'\x00ভাগকৃত', 'ভোগকৃত'),

        # কার্যালয়
        (r'কাযা[\x00\s]*লয়', 'কার্যালয়'),
        (r'কাযা[\x00\s]*ল', 'কার্যাল'),

        # কর্মস্থল
        (r'কমস্থ[\x00\s]*ল', 'কর্মস্থল'),
        (r'কমস্থ[\x00\s]*', 'কর্মস্থল '),

        # ত্যাগের / ত্যাগ
        (r'ত[\x00\s]*ােগর', 'ত্যাগের'),
        (r'ত[\x00\s]*ভােগ', 'ত্যাগে'),
        (r'ত[\x00\s]*ভাগ', 'ত্যাগ'),

        # জন্য (safely matching isolated জন or জন\x00 without touching জনাব)
        (r'(?<![\u0980-\u09FF])জন[\x00\s]*(?![\u0980-\u09FF])', 'জন্য'),
        (r'জন\x00', 'জন্য'),

        # সম্মানপূর্বক
        (r'স[\x00\s]*ানপবূ[\s]*ক(?=[\x00\s]|$)', 'সম্মানপূর্বক'),
        (r'স[\x00\s]*ানপূব্[\s]*ক(?=[\x00\s]|$)', 'সম্মানপূর্বক'),

        # যে (only when standalone, never inside conjuncts like 'ব্য', 'ত্য', 'ন্য')
        (r'(?<![\u0980-\u09FF])য(?=[,\s])', 'যে'),

        # ব্যক্তিগত
        (r'ব[\x00\s]*িক্তগত', 'ব্যক্তিগত'),

        # জরুরি
        (r'জর[\x00\s]*ির', 'জরুরি'),

        # পর্যন্ত
        (r'পযন্ত[\x00\s]*', 'পর্যন্ত'),

        # অফিসার-আইটি / আইটি
        (r'অিফসার-আই[\x00\s]*ট(?![\u0980-\u09FF])', 'অফিসার-আইটি'),
        (r'আই[\x00\s]*ট(?![\u0980-\u09FF])', 'আইটি'),

        # উল্লেখ্য / উল্লেখ
        (r'উে[\x00\s]*খ[\x00\s]*', 'উল্লেখ্য'),

        # মঞ্জুরপূর্বক / মঞ্জুরীর / মঞ্জুর
        (r'ম[\x00\s]*রু\s*পবূ[\s]*ক', 'মঞ্জুরপূর্বক'),
        (r'ম[\x00\s]*রু[\s]*ীর', 'মঞ্জুরীর'),
        (r'ম[\x00\s]*রু', 'মঞ্জুর'),

        # মোবাইল
        (r'[\x00\s]*মাবাইল', 'মোবাইল'),

        # নথি নং
        (r'নিথ\s*নং', 'নথি নং'),

        # সেল ইনচার্জ / ইনচার্জ
        (r'[\x00\s]*সল\s*ইনচাজ[\x00\s]*', 'সেল ইনচার্জ'),
        (r'ইনচাজ[\x00\s]*', 'ইনচার্জ'),

        # এজিএম / ডিজিএম
        (r'এিজএম', 'এজিএম'),
        (r'িডিজএম', 'ডিজিএম'),

        # Strip all remaining null bytes
        (r'\x00', ''),
    ]

    for pat, rep in ligature_fixes:
        text = re.sub(pat, rep, text)

    # 4. Specific vocabulary normalization for Chrome/Skia visual ordering
    vocab_fixes = [
        (r'মেহাদয়', 'মহোদয়'),
        (r'প্রেয়াজেন', 'প্রয়োজনে'),
        (r'প্রেয়াজন', 'প্রয়োজন'),
        (r'অনমুিতসহ', 'অনুমতিসহ'),
        (r'অনমু\s*িতসহ', 'অনুমতিসহ'),
        (r'অনকুূেল', 'অনুকূলে'),
        (r'অনকু\s*ূ\s*েল', 'অনুকূলে'),
        (r'অবিশষ্ট', 'অবশিষ্ট'),
        (r'সপুািরশ', 'সুপারিশ'),
        (r'সপু\s*ািরশ', 'সুপারিশ'),
        (r'হেলা', 'হলো'),
        (r'বািধত', 'বাধিত'),
        (r'পািরবািরক', 'পারিবারিক'),
        (r'িহেসেব', 'হিসেবে'),
        (r'িহসেব', 'হিসেবে'),
        (r'অিতিরক্ত', 'অতিরিক্ত'),
        (r'িপএলিস', 'পিএলসি'),
        (r'িবেশষ', 'বিশেষ'),
        (r'আেবদন', 'আবেদন'),
        (r'িনেবদন', 'নিবেদন'),
        (r'িবনীত', 'বিনীত'),
        (r'িববরণ', 'বিবরণ'),
        (r'িতন', 'তিন'),
        (r'িদেনর', 'দিনের'),
        (r'দািয়ত্ব', 'দায়িত্ব'),
        (r'দািয়েত্বর', 'দায়িত্বের'),
        (r'আিরফু ল', 'আরিফুল'),
        (r'িসিনয়র', 'সিনিয়র'),
        (r'অিফসার', 'অফিসার'),
        (r'তািরখ', 'তারিখ'),
        (r'সােলর', 'সালের'),
        (r'করেবন', 'করবেন'),
        (r'করিছ', 'করছি'),
        (r'যথািবিহত', 'যথাবিহিত'),
        (r'সমীেপ', 'সমীপে'),
        (r'সমীেপঃ', 'সমীপেঃ'),
        (r'িবষয়ঃ', 'বিষয়ঃ'),
        (r'আিম', 'আমি'),
        (r'িনজ', 'নিজ'),
        (r'িবশ্বস্ত', 'বিশ্বস্ত'),
        (r'আইিডঃ', 'আইডিঃ'),
    ]

    for pat, rep in vocab_fixes:
        text = re.sub(pat, rep, text)

    # 5. Clean up duplicate consecutive identical vowel signs
    text = re.sub(r'ি{2,}', 'ি', text)
    text = re.sub(r'ে{2,}', 'ে', text)
    text = re.sub(r'া{2,}', 'া', text)

    return text
